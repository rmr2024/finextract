"""Field definitions: what we extract, how XBRL labels it, and how we search for it."""
from dataclasses import dataclass, field


@dataclass(frozen=True)
class Field:
    name: str
    description: str
    xbrl_tags: tuple          # us-gaap tags, in priority order
    period: str               # "duration" (income/cash-flow) or "instant" (balance sheet)
    unit: str = "USD"         # XBRL unit key
    query: str = ""           # keywords for retrieval
    aliases: tuple = field(default_factory=tuple)  # line-item names used by the heuristic baseline


